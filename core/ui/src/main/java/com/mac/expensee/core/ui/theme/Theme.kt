/**
 * [dynamicColor] defaults to `false`: on Android 12+, `true` derives every color role from the
 * device's wallpaper (Material You). That's appealing in theory, but it means contrast and
 * brand consistency become wallpaper-dependent rather than something the app controls -- a light
 * or pastel wallpaper can produce a washed-out, low-contrast "dark" scheme with no code change on
 * our end. [DarkColorScheme]/[LightColorScheme] above are deliberately fully-specified so every
 * screen gets the same, tested contrast regardless of device. Callers that still want Material You
 * can opt in explicitly by passing `dynamicColor = true`.
 */
@Composable
fun ExpenseeTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.primary.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
